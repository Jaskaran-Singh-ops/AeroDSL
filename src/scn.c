/*
 * Scenario-file backend (SPEC section 13).
 *
 * Lowers the simulation trace into a flat, timestamped command list: the
 * artefact this project exists to stop people writing by hand.
 *
 * Because the output is produced from a run, conditionals and loops have
 * already been resolved: what comes out is one concrete scenario, not a
 * program. For scenario generation that is the intent -- the simulator wants
 * a scenario -- but it means the output is only as faithful as this
 * prototype's flight model, and it is not a translation of the AeroDSL
 * program's full semantics.
 *
 * The line format and the command names are BlueSky's .scn format. The files
 * generated for the examples load and run in BlueSky 1.1.1 (bluesky/README.md);
 * other versions have not been tried. Times come from this prototype's flight
 * model, so a wait can resolve earlier or later than BlueSky's own model.
 */
#include <math.h>

#include "aerodsl.h"

void scn_format_alt(double ft, char *buf, size_t n) {
    double hundreds = ft / 100.0;
    if (ft >= 1000 && fabs(hundreds - floor(hundreds + 0.5)) < 1e-9)
        snprintf(buf, n, "FL%03d", (int)floor(hundreds + 0.5));
    else
        snprintf(buf, n, "%.0f", ft);
}

/* HH:MM:SS.hh, the timestamp form a scenario file uses. */
static void fmt_stamp(double t, char *buf, size_t n) {
    if (!(t > 0)) t = 0;
    if (t > 359999) t = 359999; /* the field carries at most 99 hours */
    unsigned total = (unsigned)t;
    unsigned cs = (unsigned)((t - (double)total) * 100.0 + 0.5);
    if (cs >= 100) {
        total++;
        cs -= 100;
    }
    unsigned h = (total / 3600) % 100, m = (total / 60) % 60, s = total % 60;
    snprintf(buf, n, "%02u:%02u:%02u.%02u", h, m, s, cs % 100);
}

void scn_emit(FILE *f, const Program *p, const VmResult *r) {
    char title[128], stamp[24], name[32], arg[32];

    fprintf(f, "# Scenario generated by the AeroDSL compiler\n");
    fprintf(f, "# Source scenario: \"%s\"\n", str_cstr(p->scenario, title, sizeof title));
    fprintf(f, "#\n");
    fprintf(f, "# A flat timestamped command list in BlueSky's .scn format.\n");
    fprintf(f, "# Conditionals and loops in the source were resolved by simulating it, so\n");
    fprintf(f, "# this is one concrete scenario rather than a program. Tested with\n");
    fprintf(f, "# BlueSky 1.1.1; other simulator versions are not verified.\n");
    fprintf(f, "#\n");
    int entries = 0, clearances = 0;
    for (int i = 0; i < r->events.count; i++) {
        if (r->events.items[i].kind == EV_ENTER) entries++;
        if (r->events.items[i].kind == EV_CLEAR) clearances++;
    }
    fprintf(f, "# %.0f s of simulated time, %d aircraft, %d clearance%s, %d loss%s of "
               "separation.\n",
            r->t, entries, clearances, clearances == 1 ? "" : "s", r->los_count,
            r->los_count == 1 ? "" : "es");
    fprintf(f, "# Not for operational use.\n\n");

    /* Waypoint definitions first, so the commands that name them resolve. */
    fmt_stamp(0, stamp, sizeof stamp);
    for (int i = 0; i < p->nfixes; i++)
        fprintf(f, "%s>DEFWPT %s,%.6f,%.6f\n", stamp, str_cstr(p->fixes[i].name, name, sizeof name),
                p->fixes[i].lat, p->fixes[i].lon);
    if (p->nfixes) fputc('\n', f);

    for (int i = 0; i < r->events.count; i++) {
        const Event *e = &r->events.items[i];
        if (e->kind != EV_ENTER && e->kind != EV_CLEAR) continue;
        fmt_stamp(e->t, stamp, sizeof stamp);

        if (e->kind == EV_ENTER) {
            fprintf(f, "%s>CRE %s,%s\n", stamp,
                    str_cstr(p->flights[e->flight].name, name, sizeof name), e->text);
            continue;
        }

        const char *cs = str_cstr(p->flights[e->flight].name, name, sizeof name);
        switch (e->clear) {
        case CL_CLIMB:
        case CL_DESCEND:
            scn_format_alt(e->value, arg, sizeof arg);
            fprintf(f, "%s>ALT %s,%s\n", stamp, cs, arg);
            break;
        case CL_HEADING: fprintf(f, "%s>HDG %s,%.0f\n", stamp, cs, e->value); break;
        case CL_SPEED: fprintf(f, "%s>SPD %s,%.0f\n", stamp, cs, e->value); break;
        case CL_DIRECT: {
            int fx = (int)e->value;
            if (fx >= 0 && fx < p->nfixes)
                fprintf(f, "%s>ADDWPT %s,%s\n", stamp, cs,
                        str_cstr(p->fixes[fx].name, arg, sizeof arg));
            break;
        }
        default: break;
        }
    }
}
